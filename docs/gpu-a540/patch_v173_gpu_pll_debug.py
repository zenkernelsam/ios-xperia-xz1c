#!/usr/bin/env python3
# v173: PLL0 diagnosis. Read XO branch and all PLL registers before/after
# configuration, configure USER_CTL postdiv, wait 5 ms for lock. If it still
# does not lock, retry gfx3d from GPLL0 (src=5) before touching RBBM.
import os

ROOT = '/Users/ciscohe/Desktop/ios-xperia-xz1c/dxb/xnu'
p = os.path.join(ROOT, 'bsd/dev/sweet_gpu.c')
s = open(p).read()
start = s.index('\tif (level >= 6) {')
end = s.index('\tint pause = 0;', start)
block = (
    '\tif (level >= 6) {\n'
    '\t\tvm_offset_t gpuc = ml_io_map(GPUCC_PA, 0x2000);\n'
    '\t\tvm_offset_t gpu = ml_io_map(0x05000000u, 0x00040000u);\n'
    '\t\tprintf("SWEET GPU: l6 gpuc=%#lx gpu=%#lx\\n", gpuc, gpu);\n'
    '\t\tif (gpuc) {\n'
    '\t\t\tgpu_wr(gpuc, 0x1004, 0x222000u);\n'
    '\t\t\tdelay(10);\n'
    '\t\t\tgpu_wr(gpuc, 0x1090, 0x1u);\n'
    '\t\t\tdelay(1);\n'
    '\t\t\tgpu_wr(gpuc, 0x1090, 0x0u);\n'
    '\t\t\tgpu_wr(gpuc, 0x0130, 0x11u);\n'
    '\t\t\tdelay(1);\n'
    '\t\t\tgpu_wr(gpuc, 0x0130, 0x01u);\n'
    '\t\t\tdelay(1);\n'
    '\t\t\tgpu_wr(gpuc, 0x0130, 0x00u);\n'
    '\t\t\tgpu_wr(gpuc, 0x1094, 0x222000u);\n'
    '\t\t\tdelay(10);\n'
    '\t\t\tprintf("SWEET GPU: GDSC CX=%#x GX=%#x xo_branch=%#x\\n",\n'
    '\t\t\t    gpu_rd(gpuc, 0x1004), gpu_rd(gpuc, 0x1094),\n'
    '\t\t\t    gpu_rd(gpuc, 0x1020));\n'
    '\t\t\tprintf("SWEET GPU: PLL pre mode=%#x op=%#x l=%#x cal=%#x frac=%#x\\n",\n'
    '\t\t\t    gpu_rd(gpuc, 0x0000), gpu_rd(gpuc, 0x002c),\n'
    '\t\t\t    gpu_rd(gpuc, 0x0004), gpu_rd(gpuc, 0x0008),\n'
    '\t\t\t    gpu_rd(gpuc, 0x0038));\n'
    '\t\t\tgpu_wr(gpuc, 0x0004, 0x12u);\n'
    '\t\t\tgpu_wr(gpuc, 0x0008, 0x3fu);\n'
    '\t\t\tgpu_wr(gpuc, 0x0038, 0xc00u);\n'
    '\t\t\tgpu_wr(gpuc, 0x0014, 0x20485699u);\n'
    '\t\t\tgpu_wr(gpuc, 0x0018, 0x2067u);\n'
    '\t\t\tgpu_wr(gpuc, 0x0010, 0x4805u);\n'
    '\t\t\tgpu_wr(gpuc, 0x000c, 0x7u);\n'
    '\t\t\tprintf("SWEET GPU: PLL rb l=%#x cal=%#x frac=%#x cfg=%#x uctl=%#x\\n",\n'
    '\t\t\t    gpu_rd(gpuc, 0x0004), gpu_rd(gpuc, 0x0008),\n'
    '\t\t\t    gpu_rd(gpuc, 0x0038), gpu_rd(gpuc, 0x0014),\n'
    '\t\t\t    gpu_rd(gpuc, 0x000c));\n'
    '\t\t\tuint32_t mode = gpu_rd(gpuc, 0x0000);\n'
    '\t\t\tgpu_wr(gpuc, 0x0000, mode & ~1u);\n'
    '\t\t\tgpu_wr(gpuc, 0x002c, 0x0u);\n'
    '\t\t\tdelay(1);\n'
    '\t\t\tgpu_wr(gpuc, 0x0000, (mode & ~1u) | 0x4u);\n'
    '\t\t\tgpu_wr(gpuc, 0x002c, 0x1u);\n'
    '\t\t\tint locked = 0;\n'
    '\t\t\tfor (int i = 0; i < 5000; ++i) {\n'
    '\t\t\t\tif (gpu_rd(gpuc, 0x0024) & 0x80000000u) {\n'
    '\t\t\t\t\tlocked = 1;\n'
    '\t\t\t\t\tbreak;\n'
    '\t\t\t\t}\n'
    '\t\t\t\tdelay(1);\n'
    '\t\t\t}\n'
    '\t\t\tuint32_t uctl = gpu_rd(gpuc, 0x000c);\n'
    '\t\t\tgpu_wr(gpuc, 0x000c, uctl | 0x7u);\n'
    '\t\t\tmode = gpu_rd(gpuc, 0x0000);\n'
    '\t\t\tgpu_wr(gpuc, 0x0000, mode | 0x1u);\n'
    '\t\t\tprintf("SWEET GPU: PLL lock=%d mode=%#x op=%#x status=%#x\\n",\n'
    '\t\t\t    locked, gpu_rd(gpuc, 0x0000), gpu_rd(gpuc, 0x002c),\n'
    '\t\t\t    gpu_rd(gpuc, 0x0024));\n'
    '\t\t\tif (locked) {\n'
    '\t\t\t\tgpu_wr(gpuc, 0x1078, 0x0u);\n'
    '\t\t\t\tgpu_wr(gpuc, 0x107c, 0xffffffffu);\n'
    '\t\t\t\tgpu_wr(gpuc, 0x1080, 0xffffffffu);\n'
    '\t\t\t\tgpu_wr(gpuc, 0x1074, 0x101u);\n'
    '\t\t\t\tgpu_wr(gpuc, 0x1070, 0x0u);\n'
    '\t\t\t\tdelay(10);\n'
    '\t\t\t\tgpu_wr(gpuc, 0x1098, 0x1u);\n'
    '\t\t\t\tdelay(10);\n'
    '\t\t\t\tprintf("SWEET GPU: RCG cmd=%#x cfg=%#x branch=%#x\\n",\n'
    '\t\t\t\t    gpu_rd(gpuc, 0x1070), gpu_rd(gpuc, 0x1074),\n'
    '\t\t\t\t    gpu_rd(gpuc, 0x1098));\n'
    '\t\t\t} else {\n'
    '\t\t\t\t/* Fallback: gfx3d from GPLL0 (src 5), divide by 2. */\n'
    '\t\t\t\tgpu_wr(gpuc, 0x1074, 0x501u);\n'
    '\t\t\t\tgpu_wr(gpuc, 0x1070, 0x0u);\n'
    '\t\t\t\tdelay(10);\n'
    '\t\t\t\tgpu_wr(gpuc, 0x1098, 0x1u);\n'
    '\t\t\t\tdelay(10);\n'
    '\t\t\t\tprintf("SWEET GPU: fallback RCG cmd=%#x cfg=%#x branch=%#x\\n",\n'
    '\t\t\t\t    gpu_rd(gpuc, 0x1070), gpu_rd(gpuc, 0x1074),\n'
    '\t\t\t\t    gpu_rd(gpuc, 0x1098));\n'
    '\t\t\t}\n'
    '\t\t\tif (gpu) {\n'
    '\t\t\t\tprintf("SWEET GPU: reading RBBM\\n");\n'
    '\t\t\t\tuint32_t rbbm = gpu_rd(gpu, 0x4f5);\n'
    '\t\t\t\tprintf("SWEET GPU: RBBM_STATUS %#x\\n", rbbm);\n'
    '\t\t\t}\n'
    '\t\t}\n'
    '\t}\n\n'
)
s = s[:start] + block + s[end:]
open(p, 'w').write(s)
print('v173 applied')
